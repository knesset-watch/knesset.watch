/**
 * Prompt for bottom-up policy analysis of a bill.
 *
 * שונה מהותית מ-classify-bill-agendas-llm.ts. שם השאלה היא "לאיזו
 * אג'נדה מתוך רשימה נתונה שייך החוק"; כאן השאלה היא "מה החוק משנה,
 * ומהי המחלוקת שהוא מגלם" — בלי רשימה נתונה.
 *
 * הטקסונומיה תיגזר בהמשך מלמטה, מכלל הניתוחים. לכן אסור לכפות כאן
 * את POLITICAL_ISSUES הקיימות: הן היו מגבילות את מרחב התשובות
 * לשתים-עשרה סוגיות שכבר הגדרנו, וזו בדיוק ההטיה שאנחנו מנסים לעקוף.
 */

export const ANALYSIS_VERSION = 'fulltext-v1';

/**
 * תקרת הטקסט הנשלחת. 30,000 תווים מכסים 97% מהחוקים במלואם — החציון
 * הוא 2,759 והאחוזון ה-90 הוא 9,316. רק 204 חוקים חורגים, והם מסומנים
 * needs_review כדי שנדע שהניתוח שלהם חלקי.
 */
export const MAX_TEXT_CHARS = 30_000;

export interface BillForAnalysis {
  id: number;
  title: string;
  committee_name: string | null;
  text_content: string;
  is_gazette: boolean;
}

const SYSTEM_RULES = `אתה אנליסט מדיניות. אתה מקבל נוסח של הצעת חוק ישראלית ומפיק ניתוח מובנה.

מה לעשות:
1. לזהות מה ההסדר הקיים היום, כפי שהוא עולה מהנוסח.
2. לזהות מה ההצעה משנה ביחס אליו.
3. לנסח את שאלת המדיניות שהשינוי הזה מגלם.
4. לנסח את העמדה שתמיכה בשינוי מייצגת.
5. לנסח את העמדה הנגדית הסבירה.

כללים מחייבים:

- הניתוח חייב לנבוע מהוראות החוק עצמן. אל תסתמך על הכותרת בלבד.
- אל תמציא אידאולוגיה שאינה עולה מהנוסח. אם ההצעה טכנית, אמור זאת.
- con_stance הוא ההיפך הסביר. כשאין חלופה מפורשת בחוק, הנסח המינימלי
  הוא התנגדות לשינוי ושמירה על ההסדר הקיים. זה תקין ואינו חולשה.
- issue_candidate הוא שם קצר וכללי לשאלת המדיניות, שאפשר יהיה לחזור
  עליו בחוקים אחרים. אסור שיהיה שם החוק.
  רע:  "תיקון מס' 18 לחוק הביטוח הלאומי"
  טוב: "זכאות עצמאים לדמי אבטלה"
- חוק אחד יכול להכיל כמה שינויי מדיניות עצמאיים. צור רשומה נפרדת לכל
  שאלת מדיניות שונה באמת. אל תפצל פרטי יישום טכניים.
- לכל סוגיה צרף ראיה: ציטוט קצר מהנוסח, ומספר סעיף אם קיים. הציטוט
  חייב להופיע מילה במילה בטקסט שקיבלת.
- confidence הוא 0 עד 1, ומשקף עד כמה הנוסח תומך בניתוח.
- needs_review = true כשהטקסט חלקי, משובש, או כשאינך בטוח שזיהית את
  עיקר ההצעה.

החזר JSON תקין בלבד, בלי טקסט לפניו או אחריו, בלי גדרות קוד.`;

const OUTPUT_SHAPE = `{
  "bill_id": <number>,
  "summary": "<מה ההצעה עושה, במשפט או שניים>",
  "issues": [
    {
      "domain_candidate": "<תחום רחב, למשל 'רווחה' או 'משפט פלילי'>",
      "issue_candidate": "<שם קצר וכללי לשאלת המדיניות>",
      "policy_change": "<מה משתנה ביחס להסדר הקיים>",
      "pro_stance": "<העמדה שתמיכה בשינוי מייצגת>",
      "con_stance": "<העמדה הנגדית הסבירה>",
      "explanation": "<למה זו שאלת המדיניות, על סמך הנוסח>",
      "evidence": [ { "section": "<מספר סעיף או null>", "text": "<ציטוט קצר מהנוסח>" } ],
      "confidence": <0..1>,
      "is_primary": <true לסוגיה המרכזית, false לשאר>
    }
  ],
  "needs_review": <boolean>
}`;

export function buildPrompt(bill: BillForAnalysis): string {
  const text = bill.text_content.slice(0, MAX_TEXT_CHARS);
  const truncated = bill.text_content.length > MAX_TEXT_CHARS;

  /**
   * 502 מהמסמכים הם גיליון "רשומות" שמכיל עשרות הצעות חוק. בלי האזהרה
   * הזו המודל מנתח את ההצעה הראשונה בגיליון במקום את זו שהתבקשה.
   */
  const gazetteWarning = bill.is_gazette
    ? `\n\nשים לב: המסמך הוא גיליון רשומות המכיל כמה הצעות חוק. נתח אך ורק את ההצעה שכותרתה מופיעה למעלה, והתעלם משאר ההצעות בגיליון. אם אינך מוצא אותה בטקסט, החזר issues ריק ו-needs_review = true.`
    : '';

  const truncationWarning = truncated
    ? `\n\nשים לב: הטקסט נחתך בשל אורכו. אם נראה שחסר חלק מהותי, סמן needs_review = true.`
    : '';

  return `${SYSTEM_RULES}

מבנה הפלט:
${OUTPUT_SHAPE}

────────────────────────
מזהה החוק: ${bill.id}
כותרת: ${bill.title}
ועדה: ${bill.committee_name ?? 'לא ידוע'}${gazetteWarning}${truncationWarning}

נוסח ההצעה:
${text}
────────────────────────

החזר JSON בלבד.`;
}
