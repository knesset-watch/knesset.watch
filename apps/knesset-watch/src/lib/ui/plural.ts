/**
 * צורת רבים בעברית. "1 שאלות" אינו תקין, ו-1 הוא מקרה שכיח כאן:
 * לאשכול "התיישבות וריבונות" יש בדיוק שאלה אחת.
 *
 * העברית מבחינה בין יחיד לרבים בלבד בהקשר הזה, ולכן שני ארגומנטים.
 * המספר אינו מוצג ביחיד — "שאלה אחת" ולא "1 שאלה".
 */
export function countLabel(n: number, one: string, many: string): string {
  return n === 1 ? one : `${n.toLocaleString()} ${many}`;
}
